/* 4. Шаблоны ответов (прототип вместо LLM) */
export const AGENT_TEMPLATES = {
  greet: (name: string) => `Привет, ${name || "друг"}! Я ваш AI-партнёр. Чем помочь — подобрать, сравнить, собрать проект или просто поболтать о стиле?`,
  photoAck: "Принял фото. Ищу похожие изделия по всему сервису…",
  photoFound: (n: number) => `Нашёл ${n} похожих позиций. Показываю карточки ниже — если нужно точь-в-точь, могу оформить индивидуальный заказ.`,
  priceSuggest: (prod: string, price: number, avg: number) => {
    const delta = Math.round(((price - avg) / avg) * 100);
    return delta > 10
      ? `«${prod}» сейчас на ${delta}% выше средней по нише. Подумайте о скидке или улучшении карточки.`
      : delta < -10
      ? `«${prod}» ниже рынка на ${Math.abs(delta)}%. Можно поднять цену без потери спроса.`
      : `Цена «${prod}» в рыночном коридоре. Альтернативы не требуются.`;
  },
  demand: (niche: string, trend: "up" | "down" | "flat") =>
    trend === "up" ? `Спрос в нише «${niche}» растёт — пора расширять ассортимент.`
    : trend === "down" ? `Спрос в нише «${niche}» снизился — рассмотрите скидку или новые теги.`
    : `Спрос в нише «${niche}» стабилен. Продолжаем в том же ритме.`,
  mindful: (dup: string) => `Похоже, «${dup}» у вас уже есть в избранном/корзине. Дубликат? Если это осознанный выбор — ок, иначе можно пропустить.`,
  confirmOrder: (items: number, total: number) => `Собрал заказ: ${items} поз. на ${total.toLocaleString("ru-RU")} ₽. Подтвердить?`,
  confirmCustom: "Черновик индивидуального заказа готов с вашим фото. Отправить мастеру?",
};

/* 5. Функция обучения (по фидбеку) */
export const agentLearn = (profile: Record<string, unknown>, signal: { type: string; payload: Record<string, unknown> }): Record<string, unknown> => {
  const p = { ...profile, feedbacks: [signal, ...((profile.feedbacks as unknown[]) || []).slice(0, 49)] };
  return p;
};
