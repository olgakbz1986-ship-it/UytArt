export function aiPickProducts(query: string, count = 6): Product[] {
  const q = query.toLowerCase();
  const scored = PRODUCTS.map((p) => {
    let score = 0;
    const c = catBySlug(p.categoryId);
    const g = c ? groupById(c.group) : undefined;
    if (p.name.toLowerCase().includes(q)) score += 5;
    if (p.material.toLowerCase().includes(q)) score += 3;
    if (p.style.toLowerCase().includes(q)) score += 3;
    if (p.tags.some((t) => q.includes(t.toLowerCase()) || t.toLowerCase().includes(q))) score += 2;
    if (c?.name.toLowerCase().includes(q)) score += 2;
    if (g?.name.toLowerCase().includes(q)) score += 1;
    return { p, score };
  }).sort((a, b) => b.score - a.score || b.p.rating - a.p.rating);
  return scored.slice(0, count).map((s) => s.p);
}

