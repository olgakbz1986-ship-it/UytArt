const STYLES = ["Сканди", "Лофт", "Джапанди", "Неоклассика", "Бохо", "Минимализм", "Прованс", "Эко"];
const COLORS = ["молочный", "шалфей", "терракота", "графит", "охра", "индиго", "пудровый", "орех"];
const ADJ = ["Авторская", "Тёплая", "Утренняя", "Северная", "Лесная", "Домашняя", "Ремесленная", "Тихая"];
const rnd = (seed: number) => {
  let x = Math.sin(seed) * 10000;
  return x - Math.floor(x);
};
const daysAgo = (n: number) => new Date(Date.now() - n * 864e5).toISOString();

function genProducts(): Product[] {
  const out: Product[] = [];
  let id = 1;
  CATEGORIES.forEach((c, ci) => {
    const vendorsInGroup = VENDORS.filter((v) => v.id === "v" + ((ci % VENDORS.length) + 1));
    const vendor = vendorsInGroup[0] || VENDORS[ci % VENDORS.length];
    const mats = MATERIALS[c.group] || ["натуральные материалы"];
    const perCat = 5;
    for (let i = 0; i < perCat; i++) {
      const seedNum = ci * 100 + i;
      const material = mats[Math.floor(rnd(seedNum + 1) * mats.length)];
      const style = STYLES[Math.floor(rnd(seedNum + 2) * STYLES.length)];
      const color = COLORS[Math.floor(rnd(seedNum + 3) * COLORS.length)];
      const adj = ADJ[Math.floor(rnd(seedNum + 4) * ADJ.length)];
      const sub = c.subs[Math.floor(rnd(seedNum + 5) * c.subs.length)];
      const basePrice = 800 + Math.floor(rnd(seedNum + 6) * 120) * 100;
      const isCustom = c.group === "home" && (c.slug.includes("мебел") || c.slug.includes("зеркал")) && i % 3 === 0;
      const hasOld = rnd(seedNum + 7) > 0.65;
      const rating = Math.round((4.3 + rnd(seedNum + 8) * 0.7) * 10) / 10;
      const created = Math.floor(rnd(seedNum + 9) * 180);
      out.push({
        id: "p" + id,
        slug: `${c.slug}-${slugify(sub.name)}-${i + 1}`,
        name: `${sub.name} «${adj}»`,
        price: basePrice,
        oldPrice: hasOld ? Math.round(basePrice * 1.25) : undefined,
        categoryId: c.slug,
        vendorId: vendor.id,
        image: GROUP_IMG[c.group],
        art: [
          ["#e8dcc8", "#d9c4a3", "#e3d5bd", "#dfd0b4"][i % 4],
          ["#c9b28f", "#b8a179", "#c4ad89", "#bfa882"][i % 4],
        ],
        emoji: c.emoji,
        product_type: isCustom ? "custom_made" : "ready_made",
        production_time_days: isCustom ? 14 + Math.floor(rnd(seedNum + 10) * 14) : undefined,
        is_non_returnable: isCustom,
        rating,
        reviewsCount: 5 + Math.floor(rnd(seedNum + 11) * 90),
        description: `${sub.name} ручной работы в стиле ${style.toLowerCase()}. Материал — ${material}, цвет ${color}. Изготовлено мастером ${vendor.name} (${vendor.city}). ${isCustom ? "Изготавливается под заказ по вашим размерам, поэтому возврату не подлежит." : "Готовое изделие, отправка в течение 1–3 дней."}`,
        material,
        style,
        color,
        size: ["S", "M", "L", "40×40 см", "60×40 см", "стандарт"][Math.floor(rnd(seedNum + 12) * 6)],
        sub: sub.slug,
        sku: "UA-" + c.group.slice(0, 2).toUpperCase() + "-" + (1000 + id),
        stock: isCustom ? 0 : 1 + Math.floor(rnd(seedNum + 13) * 24),
        views: 200 + Math.floor(rnd(seedNum + 14) * 5000),
        tags: [material, style, sub.name, c.name],
        createdAt: daysAgo(created),
        isNew: created < 21,
        isHit: rating >= 4.7 && rnd(seedNum + 15) < 0.6,
      });
      id++;
    }
  });
  return out;
}
